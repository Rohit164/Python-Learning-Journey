''''
🚀 Python Dictionaries -> 


Syntax:

dictionary_name = {
    key1: value1,
    key2: value2
}
'''



student = {
    "name": 'Rohit',
    "age": 21,
    "course": 'Python',
    "city": 'Mumbai'
}

print(student)

print(f"NAME : {student['name']}")
print(f"AGE : {student['age']}")
print(f"COURSE : {student['course']}")
print(f"CITY : {student['city']}")